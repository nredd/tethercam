//! Render native syntax without shell interpolation.
//!
//! References: systemd.syntax(7), systemd.service(5), launchd.plist(5).

use super::Error;
use std::path::{Component, Path};

pub(super) const SYSUSERS: &str = "# Generated by tethercam service; do not edit.\nu tethercam - \"Tethercam service\" /var/lib/tethercam /usr/sbin/nologin\n";
pub(super) const UDEV: &str = "# Generated by tethercam service; do not edit.\nSUBSYSTEM==\"usb\", ENV{DEVTYPE}==\"usb_device\", ATTR{idVendor}==\"054c\", GROUP=\"tethercam\", MODE=\"0660\", TAG+=\"uaccess\"\n";

pub(super) fn path(value: &Path) -> Result<&str, Error> {
    let text = value.to_str().ok_or(Error::Invalid)?;
    if !value.is_absolute()
        || value
            .components()
            .any(|part| matches!(part, Component::ParentDir))
        || text
            .chars()
            .any(|value| value.is_control() || matches!(value, '\u{fffe}' | '\u{ffff}'))
    {
        return Err(Error::Invalid);
    }
    Ok(text)
}

fn xml(value: &Path) -> Result<String, Error> {
    Ok(path(value)?
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;"))
}

fn word(value: &Path, argument: bool) -> Result<String, Error> {
    let text = path(value)?;
    // systemd rejects these characters in the executable even after unquoting/C-unescaping.
    // They remain supported (and escaped) in later arguments and in launchd paths.
    if !argument && text.contains(['\'', '"', '\\']) {
        return Err(Error::Invalid);
    }
    let escaped = text
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('%', "%%");
    // systemd expands environment references in arguments, but NOT in the executable name.
    let escaped = if argument {
        escaped.replace('$', "$$")
    } else {
        escaped
    };
    Ok(format!("\"{escaped}\""))
}

pub(super) fn launchd(binary: &Path, config: &Path, logs: &Path) -> Result<String, Error> {
    let binary = xml(binary)?;
    let config = xml(config)?;
    let logs = xml(logs)?;
    let stdout = format!("{logs}/stdout.log");
    let stderr = format!("{logs}/stderr.log");
    Ok(format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n\
<!-- Generated by tethercam service; do not edit. -->\n\
<plist version=\"1.0\"><dict>\n\
<key>Label</key><string>net.tethercam.agent</string>\n\
<key>ProgramArguments</key><array><string>{binary}</string><string>run</string><string>--config</string><string>{config}</string></array>\n\
<key>KeepAlive</key><true/>\n\
<key>RunAtLoad</key><true/>\n\
<key>ExitTimeOut</key><integer>0</integer>\n\
<key>ThrottleInterval</key><integer>10</integer>\n\
<key>Umask</key><integer>63</integer>\n\
<key>StandardOutPath</key><string>{stdout}</string>\n\
<key>StandardErrorPath</key><string>{stderr}</string>\n\
</dict></plist>\n"
    ))
}

pub(super) fn systemd(binary: &Path, config: &Path, user: bool) -> Result<String, Error> {
    let binary = word(binary, false)?;
    let config = word(config, true)?;
    let hardening = if user {
        String::new()
    } else {
        format!(
            "User=tethercam\nGroup=tethercam\nProtectSystem=strict\nProtectHome=yes\nReadWritePaths={}\nDevicePolicy=closed\nDeviceAllow=char-usb_device rw\n",
            "\"/var/lib/tethercam\""
        )
    };
    let target = if user {
        "default.target"
    } else {
        "multi-user.target"
    };
    Ok(format!(
        "# Generated by tethercam service; do not edit.\n\
[Unit]\nDescription=Tethercam ONVIF bridge\nAfter=network.target\n\
[Service]\nType=simple\nExecStart={binary} run --config {config}\n\
Restart=on-failure\nRestartSec=5s\nTimeoutStopSec=infinity\nKillSignal=SIGTERM\n\
NoNewPrivileges=yes\nUMask=0077\n{hardening}\
[Install]\nWantedBy={target}\n"
    ))
}
